import joblib
import pandas as pd
import streamlit as st


# ============================================================
# PAGE SETUP
# ============================================================

st.set_page_config(
    page_title="Hotel Booking Cancellation Predictor",
    page_icon="🏨",
    layout="wide"
)


# ============================================================
# LOAD THE TRAINED PIPELINE
# ============================================================

@st.cache_resource
def load_pipeline():
    return joblib.load("hotel_cancellation_pipeline.pkl")


try:
    pipeline = load_pipeline()
except FileNotFoundError:
    st.error(
        "The file 'hotel_cancellation_pipeline.pkl' could not be found. "
        "Make sure it is saved in the same folder as app.py."
    )
    st.stop()
except Exception as error:
    st.error(f"The machine-learning pipeline could not be loaded: {error}")
    st.stop()


# ============================================================
# PAGE HEADER
# ============================================================

st.title("🏨 Hotel Booking Cancellation Predictor")

st.write(
    "Enter the booking details below to estimate the probability that "
    "the booking will be cancelled."
)

st.caption(
    "The prediction is generated by a Logistic Regression pipeline trained "
    "on 119,208 historical hotel bookings."
)

st.divider()


# ============================================================
# BOOKING INPUT FORM
# ============================================================

with st.form("booking_form"):

    st.header("Booking Details")

    left_column, middle_column, right_column = st.columns(3)

    # --------------------------------------------------------
    # COLUMN 1: Main booking information
    # --------------------------------------------------------

    with left_column:

        st.subheader("Booking Information")

        hotel = st.selectbox(
            "Hotel Type",
            ["City Hotel", "Resort Hotel"]
        )

        lead_time = st.number_input(
            "Lead Time (days)",
            min_value=0,
            max_value=750,
            value=120,
            help="Number of days between booking and arrival."
        )

        arrival_date_month = st.selectbox(
            "Arrival Month",
            [
                "January", "February", "March", "April",
                "May", "June", "July", "August",
                "September", "October", "November", "December"
            ],
            index=6
        )

        stays_in_weekend_nights = st.number_input(
            "Weekend Nights",
            min_value=0,
            max_value=20,
            value=1
        )

        stays_in_week_nights = st.number_input(
            "Week Nights",
            min_value=0,
            max_value=50,
            value=3
        )

        adults = st.number_input(
            "Adults",
            min_value=1,
            max_value=10,
            value=2
        )

        children = st.number_input(
            "Children",
            min_value=0,
            max_value=10,
            value=0
        )

        babies = st.number_input(
            "Babies",
            min_value=0,
            max_value=10,
            value=0
        )

    # --------------------------------------------------------
    # COLUMN 2: Customer and booking channel
    # --------------------------------------------------------

    with middle_column:

        st.subheader("Customer and Channel")

        market_segment = st.selectbox(
            "Market Segment",
            [
                "Online TA",
                "Offline TA/TO",
                "Direct",
                "Groups",
                "Corporate",
                "Complementary",
                "Aviation"
            ]
        )

        distribution_channel = st.selectbox(
            "Distribution Channel",
            [
                "TA/TO",
                "Direct",
                "Corporate",
                "GDS"
            ]
        )

        customer_type = st.selectbox(
            "Customer Type",
            [
                "Transient",
                "Transient-Party",
                "Contract",
                "Group"
            ]
        )

        deposit_type = st.selectbox(
            "Deposit Type",
            [
                "No Deposit",
                "Non Refund",
                "Refundable"
            ]
        )

        meal = st.selectbox(
            "Meal Type",
            [
                "BB",
                "HB",
                "SC",
                "FB",
                "Undefined"
            ]
        )

        country = st.text_input(
            "Country Code",
            value="PRT",
            help="Use a three-letter country code, such as PRT, GBR, IRL or ESP."
        ).strip().upper()

        reserved_room_type = st.selectbox(
            "Reserved Room Type",
            list("ABCDEFGHLP")
        )

        assigned_room_type = st.selectbox(
            "Assigned Room Type",
            list("ABCDEFGHIKLP")
        )

    # --------------------------------------------------------
    # COLUMN 3: Booking history and requirements
    # --------------------------------------------------------

    with right_column:

        st.subheader("Booking History")

        previous_cancellations = st.number_input(
            "Previous Cancellations",
            min_value=0,
            max_value=30,
            value=0
        )

        previous_bookings_not_canceled = st.number_input(
            "Previous Bookings Not Cancelled",
            min_value=0,
            max_value=100,
            value=0
        )

        is_repeated_guest = st.selectbox(
            "Repeated Guest",
            ["No", "Yes"]
        )

        booking_changes = st.number_input(
            "Booking Changes",
            min_value=0,
            max_value=20,
            value=0
        )

        days_in_waiting_list = st.number_input(
            "Days on Waiting List",
            min_value=0,
            max_value=400,
            value=0
        )

        adr = st.number_input(
            "Average Daily Rate",
            min_value=0.0,
            max_value=1000.0,
            value=100.0,
            step=5.0
        )

        required_car_parking_spaces = st.number_input(
            "Required Parking Spaces",
            min_value=0,
            max_value=5,
            value=0
        )

        total_of_special_requests = st.number_input(
            "Special Requests",
            min_value=0,
            max_value=5,
            value=1
        )

    # --------------------------------------------------------
    # Less important date fields
    # --------------------------------------------------------

    with st.expander("Advanced arrival-date settings"):

        date_column_1, date_column_2, date_column_3 = st.columns(3)

        with date_column_1:
            arrival_date_year = st.number_input(
                "Arrival Year",
                min_value=2015,
                max_value=2035,
                value=2017
            )

        with date_column_2:
            arrival_date_week_number = st.number_input(
                "Arrival Week Number",
                min_value=1,
                max_value=53,
                value=27
            )

        with date_column_3:
            arrival_date_day_of_month = st.number_input(
                "Arrival Day of Month",
                min_value=1,
                max_value=31,
                value=15
            )

    submitted = st.form_submit_button(
        "Predict Cancellation Risk",
        type="primary",
        use_container_width=True
    )


# ============================================================
# MAKE THE PREDICTION
# ============================================================

if submitted:

    booking_data = pd.DataFrame(
        {
            "hotel": [hotel],
            "lead_time": [lead_time],
            "arrival_date_year": [arrival_date_year],
            "arrival_date_month": [arrival_date_month],
            "arrival_date_week_number": [arrival_date_week_number],
            "arrival_date_day_of_month": [arrival_date_day_of_month],
            "stays_in_weekend_nights": [stays_in_weekend_nights],
            "stays_in_week_nights": [stays_in_week_nights],
            "adults": [adults],
            "children": [children],
            "babies": [babies],
            "meal": [meal],
            "country": [country],
            "market_segment": [market_segment],
            "distribution_channel": [distribution_channel],
            "is_repeated_guest": [1 if is_repeated_guest == "Yes" else 0],
            "previous_cancellations": [previous_cancellations],
            "previous_bookings_not_canceled": [
                previous_bookings_not_canceled
            ],
            "reserved_room_type": [reserved_room_type],
            "assigned_room_type": [assigned_room_type],
            "booking_changes": [booking_changes],
            "deposit_type": [deposit_type],
            "days_in_waiting_list": [days_in_waiting_list],
            "customer_type": [customer_type],
            "adr": [adr],
            "required_car_parking_spaces": [
                required_car_parking_spaces
            ],
            "total_of_special_requests": [
                total_of_special_requests
            ]
        }
    )

    try:
        cancellation_probability = pipeline.predict_proba(
            booking_data
        )[0][1]

        predicted_class = pipeline.predict(booking_data)[0]

        st.divider()
        st.header("Prediction Result")

        result_column, recommendation_column = st.columns([1, 1])

        with result_column:

            st.metric(
                label="Cancellation Probability",
                value=f"{cancellation_probability:.1%}"
            )

            st.progress(float(cancellation_probability))

            if cancellation_probability < 0.35:
                risk_level = "LOW RISK"
                st.success(f"🟢 {risk_level}")

            elif cancellation_probability < 0.65:
                risk_level = "MEDIUM RISK"
                st.warning(f"🟠 {risk_level}")

            else:
                risk_level = "HIGH RISK"
                st.error(f"🔴 {risk_level}")

            if predicted_class == 1:
                st.write(
                    "**Model prediction:** This booking is likely to cancel."
                )
            else:
                st.write(
                    "**Model prediction:** This booking is unlikely to cancel."
                )

        with recommendation_column:

            st.subheader("Suggested Management Response")

            if cancellation_probability >= 0.65:
                st.write(
                    """
                    - Contact the guest to reconfirm the booking.
                    - Consider requesting or verifying a deposit.
                    - Flag the booking for closer monitoring.
                    - Review room-allocation decisions carefully.
                    """
                )

            elif cancellation_probability >= 0.35:
                st.write(
                    """
                    - Send a booking reminder before arrival.
                    - Confirm important booking details.
                    - Monitor the booking if demand is high.
                    """
                )

            else:
                st.write(
                    """
                    - No immediate intervention is required.
                    - Continue with the normal confirmation process.
                    - Monitor the booking through standard procedures.
                    """
                )

        with st.expander("View the booking data sent to the model"):
            st.dataframe(booking_data, use_container_width=True)

    except Exception as error:
        st.error(
            "The prediction could not be completed. "
            f"Technical details: {error}"
        )


# ============================================================
# FOOTER
# ============================================================

st.divider()

st.caption(
    "Decision-support prototype created using Python, Streamlit, "
    "scikit-learn and Logistic Regression. Predictions should support, "
    "rather than replace, managerial judgement."
)